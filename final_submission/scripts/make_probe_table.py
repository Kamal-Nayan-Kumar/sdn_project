#!/usr/bin/env python3
"""Generate tables_probe.tex + numbers_probe.tex from the boundary probe.

  python final_submission/scripts/make_probe_table.py \
      --data-dir final_submission/data \
      --out final_submission/paper/tables_probe.tex \
      --macro-out final_submission/paper/numbers_probe.tex

The boundary probe is the live experiment that puts candidate paths in
front of Gate 2 with the planner bypassed: the model's own proposals, with
and without telemetry, plus hand-crafted unsafe proposals. The prompt
robustness table records what the agent does with paraphrased,
underspecified, out-of-topology and protected-flow requests.
"""
from __future__ import annotations

import argparse
import csv
import os
import sys
from typing import Any


def load_csv(path: str) -> list[dict[str, str]]:
    with open(path, newline="", encoding="utf-8") as fh:
        return list(csv.DictReader(fh))


def esc(text: str) -> str:
    repl = {"\\": "\\textbackslash{}", "&": "\\&", "%": "\\%",
            "#": "\\#", "_": "\\_", "{": "\\{", "}": "\\}"}
    return "".join(repl.get(c, c) for c in str(text))


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--data-dir", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--macro-out", required=True)
    args = ap.parse_args()

    probe = load_csv(os.path.join(args.data_dir, "boundary_probe.csv"))
    prompts = load_csv(os.path.join(args.data_dir, "prompt_robustness.csv"))

    tel = [r for r in probe if r["source"] == "model+telemetry"]
    topo = [r for r in probe if r["source"] == "model+topology-only"]
    crafted = [r for r in probe if r["source"].startswith("crafted:")]

    def approved(rows: list[dict[str, str]]) -> int:
        return sum(1 for r in rows if r["gate2_approved"] == "True")

    def crossing(rows: list[dict[str, str]]) -> int:
        return sum(1 for r in rows if r["crosses_degraded_link"] == "True")

    def faulty_approved(rows: list[dict[str, str]]) -> int:
        return sum(1 for r in rows if r["crosses_degraded_link"] == "True"
                   and r["gate2_approved"] == "True")

    def strong(rows: list[dict[str, str]]) -> int:
        return sum(1 for r in rows if r["strong_predicate_rejects"] == "True")

    def strong_approved(rows: list[dict[str, str]]) -> int:
        return sum(1 for r in rows if r["strong_predicate_rejects"] == "True"
                   and r["gate2_approved"] == "True")

    lines: list[str] = []
    lines.append("% GENERATED by make_probe_table.py -- do not edit by hand")
    # --- Table: the boundary probe -------------------------------------
    lines.append(r"\begin{table}[t]")
    lines.append(r"\centering")
    lines.append(r"\tiny")
    lines.append(r"\caption{Gate~2 as an independent backstop, measured on the "
                 r"live lab with the planner bypassed. \emph{Model+telemetry}: "
                 r"the model is shown the effective-delay telemetry. "
                 r"\emph{Model+topology-only}: the model is shown the "
                 r"topology but not which link is degraded. \emph{Crafted}: "
                 r"hand-built unsafe proposals. \emph{Crosses fault} counts "
                 r"proposals that cross the degraded bottleneck; \emph{strong "
                 r"predicate} counts the ones the proposed excess-delay "
                 r"predicate would reject. From "
                 r"\texttt{final\_submission/data/boundary\_probe.csv}.}")
    lines.append(r"\label{tab:probe}")
    lines.append(r"\begin{tabular}{llrrrr}")
    lines.append(r"\toprule")
    lines.append(r"Proposals & Count & Approved & Rejected & Crosses fault & "
                 r"Excess-delay \\")
    lines.append(r"\midrule")
    for label, rows in (("model + telemetry", tel),
                        ("model + topology only", topo),
                        ("crafted unsafe", crafted)):
        lines.append(f"{label} & {len(rows)} & {approved(rows)} & "
                     f"{len(rows) - approved(rows)} & {crossing(rows)} & "
                     f"{strong(rows)} \\\\")
    lines.append(r"\bottomrule")
    lines.append(r"\end{tabular}")
    lines.append(r"\end{table}")
    lines.append("")

    # --- Table: prompt robustness --------------------------------------
    lines.append(r"\begin{table}[t]")
    lines.append(r"\centering")
    lines.append(r"\scriptsize")
    lines.append(r"\caption{Prompt robustness: the agent's recorded outcome "
                 r"for paraphrased, underspecified, out-of-topology and "
                 r"protected-flow requests. \emph{Parsed} is the intent tuple "
                 r"the model extracted. The clarification branch and the "
                 r"guardrail refusal are distinct, auditable outcomes. From "
                 r"\texttt{final\_submission/data/prompt\_robustness.csv}.}")
    lines.append(r"\label{tab:prompts}")
    lines.append(r"\begin{tabular}{llll}")
    lines.append(r"\toprule")
    lines.append(r"Request & Outcome & Parsed (src, dst, $\tau$) & "
                 r"Tokens \\")
    lines.append(r"\midrule")
    for r in prompts:
        parsed = (f"{r['src_host']}, {r['dst_host']}, "
                  f"{r['max_latency_ms']}" if r["src_host"] else "--")
        lines.append(f"{esc(r['case'])} & \\texttt{{{esc(r['outcome'])}}} & "
                     f"{parsed} & {r['model_tokens_streamed']} \\\\")
    lines.append(r"\bottomrule")
    lines.append(r"\end{tabular}")
    lines.append(r"\end{table}")
    lines.append("")

    with open(args.out, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")

    macro_lines = [
        "% Numbers for the boundary probe (Section VIII-B).",
        "\\newcommand{\\ProbeTotal}{%d}" % len(probe),
        "\\newcommand{\\ProbeApproved}{%d}" % approved(probe),
        "\\newcommand{\\ProbeRejected}{%d}" % (len(probe) - approved(probe)),
        "\\newcommand{\\ProbeTelN}{%d}" % len(tel),
        "\\newcommand{\\ProbeTelApproved}{%d}" % approved(tel),
        "\\newcommand{\\ProbeTelCross}{%d}" % crossing(tel),
        "\\newcommand{\\ProbeTopoN}{%d}" % len(topo),
        "\\newcommand{\\ProbeTopoApproved}{%d}" % approved(topo),
        "\\newcommand{\\ProbeTopoCross}{%d}" % crossing(topo),
        "\\newcommand{\\ProbeTopoFaultyApproved}{%d}" % faulty_approved(topo),
        "\\newcommand{\\ProbeCraftedN}{%d}" % len(crafted),
        "\\newcommand{\\ProbeCraftedApproved}{%d}" % approved(crafted),
        "\\newcommand{\\ProbeCraftedCross}{%d}" % crossing(crafted),
        "\\newcommand{\\ProbeStrong}{%d}" % strong(probe),
        "\\newcommand{\\ProbeStrongApproved}{%d}" % strong_approved(probe),
        "\\newcommand{\\PromptCases}{%d}" % len(prompts),
    ]
    with open(args.macro_out, "w", encoding="utf-8") as fh:
        fh.write("\n".join(macro_lines) + "\n")
    print("wrote", args.out, "and", args.macro_out)
    print(f"probe: {len(probe)} proposals, {approved(probe)} approved, "
          f"{crossing(probe)} crossed the fault, {faulty_approved(probe)} of "
          f"those approved; strong predicate flags {strong(probe)} "
          f"({strong_approved(probe)} of them approved)")
    print(f"prompts: {len(prompts)} cases")
    return 0


if __name__ == "__main__":
    sys.exit(main())
